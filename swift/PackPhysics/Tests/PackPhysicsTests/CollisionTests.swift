// Port of tests/test_collision.py, same hand-computed expectations, plus a
// Python-vs-Swift depth parity spot check on seeded random pairs.

import Dispatch
import Foundation
import XCTest
@testable import PackPhysics

private func box(_ center: Vec3, _ halfExtents: Vec3, axes: Mat3 = .identity, id: String = "b") -> OBB {
    OBB(center: center, axes: axes, halfExtents: halfExtents, id: id)
}

/// Rotation about Z (Python `rotz`), stored by column.
private func rotZ(_ deg: Double) -> Mat3 {
    let r = deg * (Double.pi / 180), c = cos(r), s = sin(r)
    return Mat3(columns: Vec3(c, s, 0), Vec3(-s, c, 0), Vec3(0, 0, 1))
}

/// Rotation about X (Python `rotx`), stored by column.
private func rotX(_ deg: Double) -> Mat3 {
    let r = deg * (Double.pi / 180), c = cos(r), s = sin(r)
    return Mat3(columns: Vec3(1, 0, 0), Vec3(0, c, s), Vec3(0, -s, c))
}

private func vabs(_ v: Vec3) -> Vec3 { Vec3(abs(v.x), abs(v.y), abs(v.z)) }

/// Overlap of a/b projected on `axis` (independent of the SAT code under test).
private func projectedOverlap(_ axis: Vec3, _ a: OBB, _ b: OBB) -> Double {
    let ra = dot(vabs(a.axes.transposeMultiply(axis)), a.halfExtents)
    let rb = dot(vabs(b.axes.transposeMultiply(axis)), b.halfExtents)
    return ra + rb - abs(dot(axis, b.center - a.center))
}

private func faceAxes(_ a: OBB, _ b: OBB) -> [Vec3] {
    (0..<3).map { a.axes.column($0) } + (0..<3).map { b.axes.column($0) }
}

/// Deterministic 64-bit LCG (PCG's multiplier/increment); `SystemRandomNumberGenerator`
/// is not seedable, and the Python generator script uses these exact constants.
private struct LCG {
    private var s: UInt64
    init(seed: UInt64) { s = seed }

    mutating func next() -> Double {
        s = s &* 6364136223846793005 &+ 1442695040888963407
        return Double(s >> 11) * 0x1p-53
    }

    mutating func uniform(_ lo: Double, _ hi: Double) -> Double { lo + (hi - lo) * next() }
}

private func container() -> Container { Container(id: "c", dimensions: Vec3(4, 4, 4)) }

/// 2*nPairs random boxes; pair p is objects (2p, 2p+1). Draw order (3 quaternion, 3 dims,
/// 3 position per box) is part of the contract: `pythonDepths` below was generated by
/// replaying this exact generator in Python, so changing it invalidates that table.
private func randomObjects(count: Int) -> [SceneObject] {
    var rng = LCG(seed: 20260912)
    return (0..<count).map { k in
        let u1 = rng.next(), u2 = rng.next(), u3 = rng.next()
        let s1 = (1.0 - u1).squareRoot(), s2 = u1.squareRoot()
        let q = Quat(x: s1 * sin(2 * Double.pi * u2), y: s1 * cos(2 * Double.pi * u2),
                     z: s2 * sin(2 * Double.pi * u3), w: s2 * cos(2 * Double.pi * u3))
        let dims = Vec3(rng.uniform(0.02, 0.5), rng.uniform(0.02, 0.5), rng.uniform(0.02, 0.5))
        let pos = Vec3(rng.uniform(-0.35, 0.35), rng.uniform(-0.35, 0.35), rng.uniform(-0.35, 0.35))
        return SceneObject(id: "o\(k)", dimensions: dims, position: pos, rotation: q)
    }
}

final class CollisionTests: XCTestCase {
    // MARK: - no collision

    func testFarApart() {
        let a = box(Vec3(0, 0, 0), Vec3(1, 1, 1), id: "a")
        let b = box(Vec3(100, 100, 100), Vec3(1, 1, 1), id: "b")
        let res = checkCollision(a, b)
        XCTAssertFalse(res.colliding)
        XCTAssertEqual(res.penetrationDepthM, 0.0)
        XCTAssertNil(res.axis)
        XCTAssertNil(res.contactPoint)
        XCTAssertEqual(res.aId, "a")
        XCTAssertEqual(res.bId, "b")
        XCTAssertFalse(aabbOverlap(a, b))
    }

    // MARK: - face-face

    func testAxisAlignedOverlap() {
        // Both 2x2x2 cubes (half-extent 1), B offset 1.5 along X: overlap = 1+1-1.5 = 0.5
        let a = box(Vec3(0, 0, 0), Vec3(1, 1, 1), id: "a")
        let b = box(Vec3(1.5, 0, 0), Vec3(1, 1, 1), id: "b")
        let res = checkCollision(a, b)
        XCTAssertTrue(res.colliding)
        XCTAssertEqual(res.penetrationDepthM, 0.5, accuracy: 1e-6)
        let axis = try! XCTUnwrap(res.axis)
        XCTAssertEqual(abs(axis.x), 1, accuracy: 1e-9)
        XCTAssertEqual(abs(axis.y), 0, accuracy: 1e-9)
        XCTAssertEqual(abs(axis.z), 0, accuracy: 1e-9)
        XCTAssertEqual(axis.x, 1, accuracy: 1e-9)  // oriented A -> B
        XCTAssertTrue(aabbOverlap(a, b))
        // Contact point: midpoint of [0.5, 1] on X, centers' midpoint elsewhere.
        let contact = try! XCTUnwrap(res.contactPoint)
        XCTAssertEqual(contact.x, 0.75, accuracy: 1e-12)
        XCTAssertEqual(contact.y, 0.0, accuracy: 1e-12)
        XCTAssertEqual(contact.z, 0.0, accuracy: 1e-12)
    }

    // MARK: - 45 degree rotation

    func testRotatedBoxCollides() throws {
        // A axis-aligned cube at origin; B same size rotated 45 deg about Z, close enough
        // along X that its rotated corner pokes into A.
        let half = (Double.pi / 4) / 2  // 45 deg about Z -> q = (0, 0, sin(22.5), cos(22.5))
        let a = try obbFrom(SceneObject(id: "a", dimensions: Vec3(2, 2, 2), position: Vec3(0, 0, 0)))
        let b = try obbFrom(SceneObject(id: "b", dimensions: Vec3(2, 2, 2), position: Vec3(1.8, 0, 0),
                                        rotation: Quat(x: 0, y: 0, z: sin(half), w: cos(half))))
        let res = checkCollision(a, b)
        XCTAssertTrue(res.colliding)
        XCTAssertGreaterThan(res.penetrationDepthM, 0.0)
    }

    func testRotatedBoxNoCollisionWhenFar() throws {
        let half = (Double.pi / 4) / 2
        let a = try obbFrom(SceneObject(id: "a", dimensions: Vec3(2, 2, 2), position: Vec3(0, 0, 0)))
        let b = try obbFrom(SceneObject(id: "b", dimensions: Vec3(2, 2, 2), position: Vec3(5, 0, 0),
                                        rotation: Quat(x: 0, y: 0, z: sin(half), w: cos(half))))
        XCTAssertFalse(checkCollision(a, b).colliding)
    }

    // MARK: - containment

    func testSmallBoxInsideBigBox() throws {
        let big = box(Vec3(0, 0, 0), Vec3(5, 5, 5), id: "big")
        let small = box(Vec3(0.5, 0, 0), Vec3(1, 1, 1), id: "small")
        let res = checkCollision(big, small)
        XCTAssertTrue(res.colliding)
        // overlap along X = 5+1-0.5 = 5.5 ; Y, Z = 5+1-0 = 6 ; min is X
        XCTAssertEqual(res.penetrationDepthM, 5.5, accuracy: 1e-6)
        let axis = try XCTUnwrap(res.axis)
        XCTAssertEqual(abs(axis.x), 1, accuracy: 1e-9)
        XCTAssertEqual(abs(axis.y), 0, accuracy: 1e-9)
        XCTAssertEqual(abs(axis.z), 0, accuracy: 1e-9)
    }

    // MARK: - edge-edge (only a cross axis separates)

    /// Two rods rotated relative to each other so that only one of the 9 cross-product axes
    /// separates them -- all 6 face axes still show overlap. Verified numerically, not
    /// hand-derivable in closed form, so the assertions are booleans plus "the reported axis
    /// is not parallel to any face axis".
    private func edgeEdgePair(_ t: Double) -> (OBB, OBB) {
        let ra = Mat3.identity
        let rb = rotZ(45) * rotX(45)
        let u = cross(ra.column(0), rb.column(1))
        let un = u / length(u)
        return (OBB(center: .zero, axes: ra, halfExtents: Vec3(1.0, 0.05, 0.05), id: "a"),
                OBB(center: un * t, axes: rb, halfExtents: Vec3(0.05, 0.05, 1.0), id: "b"))
    }

    func testCollidingViaCrossAxis() throws {
        let (a, b) = edgeEdgePair(0.1)
        let res = checkCollision(a, b)
        XCTAssertTrue(res.colliding)
        let axis = try XCTUnwrap(res.axis)
        for face in faceAxes(a, b) {
            XCTAssertLessThan(abs(dot(axis, face)), 0.9)  // not (anti)parallel to a face axis
        }
    }

    func testNotCollidingButAllFaceAxesStillOverlap() {
        let (a, b) = edgeEdgePair(0.5)
        XCTAssertFalse(checkCollision(a, b).colliding)
        for face in faceAxes(a, b) {
            XCTAssertGreaterThan(projectedOverlap(face, a, b), 0.0)  // faces alone say "colliding"
        }
    }

    /// Second cross-axis-only case (30 deg about Z, 60 deg about X).
    private func edgeEdge3060Pair(_ t: Double) -> (OBB, OBB) {
        let ra = Mat3.identity
        let rb = rotZ(30) * rotX(60)
        let u = cross(ra.column(0), rb.column(2))
        let un = u / length(u)
        return (OBB(center: .zero, axes: ra, halfExtents: Vec3(1.0, 0.05, 0.05), id: "a"),
                OBB(center: un * t, axes: rb, halfExtents: Vec3(0.05, 0.05, 1.0), id: "b"))
    }

    func testEdgeEdge3060CollidingWhenClose() {
        let (a, b) = edgeEdge3060Pair(0.05)
        XCTAssertTrue(checkCollision(a, b).colliding)
    }

    func testEdgeEdge3060SeparatedOnlyByCrossAxis() {
        let (a, b) = edgeEdge3060Pair(0.2)
        XCTAssertFalse(checkCollision(a, b).colliding)
        for face in faceAxes(a, b) {
            XCTAssertGreaterThan(projectedOverlap(face, a, b), 0.0)
        }
    }

    // MARK: - corner cases

    func testExactCornerTouchNotColliding() {
        let a = box(Vec3(0, 0, 0), Vec3(1, 1, 1), id: "a")
