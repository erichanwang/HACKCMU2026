    func test100RandomPairsMatchPythonAndAreSymmetric() throws {
        let nPairs = 100
        let g = try precompute(Scene(container: container(), objects: randomObjects(count: 2 * nPairs)))
        let pairs = (0..<nPairs).map { (2 * $0, 2 * $0 + 1) }
        let batched = checkPairs(g, pairs)
        XCTAssertEqual(batched.count, nPairs)

        var nColliding = 0
        for p in 0..<nPairs {
            let a = g.obbs[2 * p], b = g.obbs[2 * p + 1]
            let res = batched[p]
            XCTAssertEqual(res, checkCollision(a, b), "pair \(p): checkPairs != checkCollision")
            XCTAssertEqual(res.aId, a.id)
            XCTAssertEqual(res.bId, b.id)

            // Python parity.
            let expected = Self.pythonDepths[p]
            XCTAssertEqual(res.colliding, expected > 0, "pair \(p): colliding disagrees with Python")
            XCTAssertEqual(res.penetrationDepthM, expected, accuracy: 1e-12, "pair \(p): depth")

            // Symmetry: same verdict, same depth, opposite MTV direction.
            let swapped = checkCollision(b, a)
            XCTAssertEqual(swapped.colliding, res.colliding, "pair \(p): asymmetric verdict")
            XCTAssertEqual(swapped.penetrationDepthM, res.penetrationDepthM, accuracy: 1e-12,
                           "pair \(p): asymmetric depth")
            if res.colliding {
                nColliding += 1
                let axis = try XCTUnwrap(res.axis)
                let back = try XCTUnwrap(swapped.axis)
                XCTAssertEqual(dot(axis, back), -1.0, accuracy: 1e-12, "pair \(p): axes not antiparallel")
                XCTAssertEqual(length(axis), 1.0, accuracy: 1e-12, "pair \(p): axis not unit")
            } else {
                XCTAssertNil(res.axis)
                XCTAssertNil(res.contactPoint)
            }

            // A box always collides with itself.
            XCTAssertTrue(checkCollision(a, a).colliding, "self-collision \(a.id)")
        }
        XCTAssertEqual(nColliding, 20)  // both branches genuinely exercised (Python agrees)
    }

    // MARK: - perf sanity

    /// Dense 20-box scene (0.20 m boxes on a 0.19 m grid + deterministic jitter -> 99 of the
    /// 190 pairs overlap). A bound, not a benchmark.
    func testDenseSceneUnderTwoMillisecondsPerCall() throws {
        let objects = (0..<20).map { k -> SceneObject in
            let grid = [k % 3, (k / 3) % 3, k / 9]
            let p = (0..<3).map { c in Double(grid[c]) * 0.19 + Double(((k * 7 + c * 3) % 11) - 5) * 0.001 }
            return SceneObject(id: "o\(k)", dimensions: Vec3(0.2, 0.2, 0.2), position: Vec3(p[0], p[1], p[2]))
        }
        let g = try precompute(Scene(container: container(), objects: objects))
        XCTAssertEqual(collideScene(g).count, 99)  // same count Python reports for this scene

        let calls = 50
        let t0 = DispatchTime.now().uptimeNanoseconds
        var total = 0
        for _ in 0..<calls { total += collideScene(g).count }
        let msPerCall = Double(DispatchTime.now().uptimeNanoseconds - t0) / 1e6 / Double(calls)
        XCTAssertEqual(total, 99 * calls)
        // Measured: 0.041 ms/call release, 1.44 ms/call debug. The -Onone build spends ~35x
        // longer on unoptimized SIMD3 arithmetic and the per-pair result array, which the 2 ms
        // target would leave no headroom for on a loaded machine -- so the debug bound is
        // loosened and only release holds the real budget.
        #if DEBUG
        let budgetMs = 8.0
        #else
        let budgetMs = 0.5
        #endif
        print("collideScene, dense 20-box scene: \(msPerCall) ms/call over \(calls) calls (budget \(budgetMs) ms)")
        XCTAssertLessThan(msPerCall, budgetMs, "collideScene took \(msPerCall) ms/call")
    }
